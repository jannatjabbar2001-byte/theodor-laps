BEGIN;

CREATE TABLE IF NOT EXISTS public.community_profiles (
    user_id INTEGER PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    display_name VARCHAR(40) NOT NULL DEFAULT '',
    avatar_filename VARCHAR(80),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.community_conversations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_low_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    member_high_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_community_conversation_members UNIQUE (member_low_id, member_high_id),
    CONSTRAINT ck_community_conversation_member_order CHECK (member_low_id < member_high_id)
);

CREATE TABLE IF NOT EXISTS public.community_memberships (
    conversation_id INTEGER NOT NULL REFERENCES public.community_conversations(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    last_read_message_id INTEGER,
    PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.community_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    conversation_id INTEGER REFERENCES public.community_conversations(id) ON DELETE CASCADE,
    reply_to_id INTEGER REFERENCES public.community_messages(id) ON DELETE SET NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    CONSTRAINT ck_community_message_expiry_scope CHECK (
        (conversation_id IS NULL AND expires_at IS NOT NULL)
        OR (conversation_id IS NOT NULL AND expires_at IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_community_conversations_member_low_id
    ON public.community_conversations(member_low_id);
CREATE INDEX IF NOT EXISTS ix_community_conversations_member_high_id
    ON public.community_conversations(member_high_id);
CREATE INDEX IF NOT EXISTS ix_community_conversations_updated_at
    ON public.community_conversations(updated_at);
CREATE INDEX IF NOT EXISTS ix_community_memberships_user_id
    ON public.community_memberships(user_id);
CREATE INDEX IF NOT EXISTS ix_community_messages_sender_id
    ON public.community_messages(sender_id);
CREATE INDEX IF NOT EXISTS ix_community_messages_conversation_id_id
    ON public.community_messages(conversation_id, id);
CREATE INDEX IF NOT EXISTS ix_community_messages_created_at
    ON public.community_messages(created_at);
CREATE INDEX IF NOT EXISTS ix_community_messages_reply_to_id
    ON public.community_messages(reply_to_id);
CREATE INDEX IF NOT EXISTS ix_community_public_message_expiry
    ON public.community_messages(expires_at)
    WHERE conversation_id IS NULL;

ALTER TABLE public.community_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_memberships ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.community_messages ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.community_profiles FROM anon, authenticated;
REVOKE ALL ON TABLE public.community_conversations FROM anon, authenticated;
REVOKE ALL ON TABLE public.community_memberships FROM anon, authenticated;
REVOKE ALL ON TABLE public.community_messages FROM anon, authenticated;

COMMIT;